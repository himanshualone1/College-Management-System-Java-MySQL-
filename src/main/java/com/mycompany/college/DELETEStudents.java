    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        // TODO add your handling code here:
        String rollNumberText = rollnumber.getText();
int rollNumber = Integer.parseInt(rollNumberText);

try {
    // Load Driver
    Class.forName("com.mysql.cj.jdbc.Driver");

    // Create Connection
    Connection con = DriverManager.getConnection("jdbc:mysql://localhost:3306/college", "root", "root");

    // Create PreparedStatement
    PreparedStatement pstm = con.prepareStatement("DELETE FROM student WHERE roll_no = ?"); 
    pstm.setInt(1, rollNumber);

    int rowsAffected = pstm.executeUpdate();
    
    if (rowsAffected > 0) {
        JOptionPane.showMessageDialog(this, "Deleted Successfully");
    } else {
        JOptionPane.showMessageDialog(this, "No record found for Roll Number: " + rollNumber);
    }

    con.close();
} catch (Exception e) {
    JOptionPane.showMessageDialog(this, e.getMessage());
}

    }//GEN-LAST:event_jButton3ActionPerformed

