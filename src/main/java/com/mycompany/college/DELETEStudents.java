        // TODO add your handling code here:
        try{
            //Load Driver
            Class.forName("com.mysql.cj.jdbc.Driver");
            //Create Connection
            Connection con = DriverManager.getConnection("jdbc:mysql://localhost:3306/college","root","root");
            //Create Statement
            PreparedStatement pstm = con.prepareStatement("Select * from student"); 
            //Execute Query
            ResultSet rs=pstm.executeQuery();
            
            DefaultTableModel model= (DefaultTableModel)Table.getModel();
           
            while(rs.next()){
                
            int sRollnumber = rs.getInt("roll_no");
            String studentRollNumber=Integer.toString(sRollnumber);
            String name = rs.getString("name");
            String class_name = rs.getString("Class");
            
            String row[]={studentRollNumber,name,class_name};
            model.addRow(row);
            }
            
            //connection close
            con.close();
            pstm.close();
            
        }catch(Exception e){
         JOptionPane.showMessageDialog(this, e);
        }
