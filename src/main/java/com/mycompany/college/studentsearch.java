    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        String studentrollnumber = rollnumber.getText();
        DefaultTableModel model = (DefaultTableModel)Table.getModel();
        if(studentrollnumber.isEmpty()){
                JOptionPane.showMessageDialog(this,  "Please enter a Roll Number to search.");
        }
        try{
            model.setRowCount(0);
            //Load Driver
            Class.forName("com.mysql.cj.jdbc.Driver");
            //Create Connection
            Connection con = DriverManager.getConnection("jdbc:mysql://localhost:3306/college","root","root");
            //Create statement 
           // Correct spelling: PreparedStatement (not PreparedStatment)
            PreparedStatement pstmt = con.prepareStatement("SELECT * FROM student WHERE roll_no = ?");

// Correct method name: setString (not setstring)
// Assuming 'studentrollnumber' is a String variable
                pstmt.setString(1, studentrollnumber);

// Execute the query
               ResultSet rs = pstmt.executeQuery();
              
               boolean hasresult= false;
               while(rs.next()){
               hasresult=true;
               int Studentrollnumber=rs.getInt("roll_no");
               String StudentRollNumber = Integer.toString(Studentrollnumber);
               String Name= rs.getString("name");
               String Class= rs.getString("Class");
               String row[]={StudentRollNumber,Name,Class};
               
               model.addRow(row);
               }
               
               if(!hasresult){
               JOptionPane.showMessageDialog(this,"No result found..");
               }

        }catch(Exception e){
            JOptionPane.showMessageDialog(this, e);
        }
    }//GEN-LAST:event_jButton2ActionPerformed

